def _despachar(args):
    """Resuelve `c_<comando>` en la fachada al ejecutar, no al construir el parser.

    Así el parser puede cachearse y `patch.object(cli, "c_estado")` sigue valiendo.
    """
    from mesa import cli as fachada
    return getattr(fachada, f"c_{args.comando}")(args)


