"""Mapas: la zona en cuadrícula y el mundo con sus lugares y rutas.

**Zona** (`escena.mapa`): el narrador la dibuja en texto, una fila por línea, con un
carácter por terreno y su leyenda. Cada casilla mide `celda` metros (1,5 por defecto, la
casilla de 5 pies de D&D); el espacio es «fuera del mapa» y los dígitos quedan para las
fichas. Las posiciones de la escena pueden llevar `celda` («C4»: columna C, fila 4) y el
visor las dibuja como fichas. El narrador lee el mismo dibujo en texto, así que ve muros,
puertas y distancias igual que los jugadores.

**Mundo** (`mundo`): lugares conocidos con coordenadas (en la unidad del mapa, km por
defecto), rutas con distancia o tiempo, y dónde están ahora. Solo lo que los personajes
conocen: lo demás sigue en director.md.

Las distancias en la cuadrícula cuentan casillas como en D&D 2024: la diagonal vale una.

La implementación está partida en módulos, pero esta fachada reexporta todo lo que
tenía: `mesa.mapas.zona_texto` sigue siendo `mesa.mapas.zona_texto`.
"""

